def test_golden_best_four_regions():
    X, y = _toy_four_regions()
    part = _find(Best(max_depth=2, min_samples_leaf=50), X, _raw_gini(y))
    assert part.to_dict() == EXPECTED_BEST_FOUR_REGIONS


def test_golden_best_level_wise_four_regions():
    X, y = _toy_four_regions()
    part = _find(BestLevelWise(max_depth=2, min_samples_leaf=50), X, _raw_gini(y))
    assert part.to_dict() == EXPECTED_BLW_FOUR_REGIONS


def test_golden_best_categorical_conditioning():
    X, y = _toy_categorical()
    part = _find(
        Best(max_depth=1, heter_small_enough=0.0),
        X,
        _raw_gini(y),
        feature_types=["cont", "cont", "cat"],
    )
    assert part.to_dict() == EXPECTED_BEST_CATEGORICAL


def test_golden_gated_pdp_end_to_end():
    data = _gated_data()
    fx = effector.PDP(data, _gated_model, nof_instances="all")
    fx.fit(0, centering=False)
    part = fx.find_regions(0, finder=Best(max_depth=2))
    assert part.to_dict() == EXPECTED_GATED_PDP
    assert [int(r.mask.sum()) for r in part] == EXPECTED_GATED_PDP_MASK_SUMS
    assert _captured_show(part) == EXPECTED_GATED_PDP_SHOW


def test_golden_root_only_best():
    X, y = _toy_four_regions()
    part = _find(
        Best(min_heterogeneity_decrease_pcg=1000.0, heter_small_enough=0.0),
        X,
        _raw_gini(y),
    )
    assert part.to_dict() == EXPECTED_ROOT_ONLY_BEST
    assert _captured_show(part) == EXPECTED_ROOT_ONLY_BEST_SHOW


def test_golden_root_only_best_level_wise_categorical_foi():
    X, y = _toy_categorical()
    part = _find(
        BestLevelWise(search_partitions_when_categorical=False),
        X,
        _raw_gini(y),
        feature=2,
        feature_types=["cont", "cont", "cat"],
        ccf=(0, 1),
    )
    assert part.to_dict() == EXPECTED_ROOT_ONLY_BLW_CAT_FOI


def test_golden_tie_break_first_candidate_wins():
    """Constant score => every candidate ties; the accepted split must stay
    the first enumerated one (ccf order x ascending positions) after the
    matrix -> flat-list rewrite."""
    X, _ = _toy_four_regions()
    part = _find(
        Best(max_depth=1, min_heterogeneity_decrease_pcg=-1.0),
        X,
        lambda mask: 1.0,
        ccf=(1, 2),
    )
    assert part.to_dict() == EXPECTED_TIE_BREAK
