AXIS_LIMITS = np.array([[0, 10], [0, 10], [0, 10]]).T
FEATURE_NAMES = ["x1", "x2", "x3"]


def _toy_four_regions():
    """Four groups defined by thresholds on feature 1 (1.5 / 3 / 5) — the
    test_unit_space_partitioning toy, verbatim."""
    np.random.seed(0)
    N, D = 1000, 3
    X = np.random.uniform(0, 10, size=(N, D))
    y = np.empty(N, dtype=int)
    for i in range(N):
        if X[i, 1] < 3:
            y[i] = 0 if X[i, 1] < 1.5 else 1
        else:
            y[i] = 2 if X[i, 1] < 5 else 3
    return X, y


def _toy_categorical():
    """Heterogeneity fully explained by the binary categorical x3."""
    np.random.seed(0)
    N = 600
    X = np.stack(
        [
            np.random.uniform(0, 10, N),
            np.random.uniform(0, 10, N),
            np.random.randint(0, 2, N).astype(float),
        ],
        axis=1,
    )
    y = X[:, 2].astype(int)
    return X, y


def _raw_gini(y):
    def score(mask):
        labels = y[mask]
        _, counts = np.unique(labels, return_counts=True)
        p = counts / counts.sum()
        return 1 - np.sum(p**2)

    return score


def _find(finder, X, score_fn, *, feature=0, feature_types=None, ccf=(0, 1, 2)):
    return finder.find_regions(
        feature=feature,
        data=X,
        score_fn=score_fn,
        axis_limits=AXIS_LIMITS,
        feature_types=feature_types,
        cat_limit=10,
        candidate_conditioning_features=list(ccf),
        feature_names=FEATURE_NAMES,
        target_name="y",
    )


def _gated_data(n=500, seed=21):
    rng = np.random.default_rng(seed)
    return np.stack(
        [
            rng.uniform(-1, 1, n),
            rng.uniform(-1, 1, n),
            rng.integers(0, 2, n).astype(float),
        ],
        axis=1,
    )


def _gated_model(x):
    y = np.zeros_like(x[:, 0])
    ind = np.logical_and(x[:, 1] > 0, x[:, 2] == 0)
    y[ind] = 5 * x[ind, 0]
    return y


def _captured_show(part):
    buf = io.StringIO()
    with redirect_stdout(buf):
        part.show()
    return buf.getvalue()


